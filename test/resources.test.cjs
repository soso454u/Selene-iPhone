test('bundled resources preserve all original fields, deduplicate, protect manual edits and verify server saves', async () => {
    const originals = Object.values(worldbook.entries);
    const unrelated = { uid: 42, comment: '用户自己的条目', content: '不可删除' };
    let storedBook = { entries: { 42: unrelated }, custom: '保留世界书配置' };
    let storedCard = { avatar: 'test.png', name: '测试角色', data: { extensions: { regex_scripts: [{ id: 'other', scriptName: '用户正则' }] } } };
    const settings = new Map(); let writes = 0; let enabled = false;
    const context = { characterId: 0, characters: [structuredClone(storedCard)], accountStorage: { getItem: key => settings.get(key), setItem: (key, value) => settings.set(key, value) }, getRequestHeaders: () => ({}) };
    const host = { document: { baseURI: 'https://tavern.test/' }, fetch: async (url, options) => {
        const body = JSON.parse(options.body);
        const route = new URL(url).pathname;
        if (route.endsWith('worldinfo/get')) return Response.json(storedBook);
        if (route.endsWith('characters/get')) return Response.json(storedCard);
        writes++;
        if (route.endsWith('worldinfo/edit')) storedBook = body.data;
        else storedCard.data.extensions.regex_scripts = body.data.extensions.regex_scripts;
        return Response.json({ ok: true });
    } };
    const manager = new Resources(host, {}, context, async () => ({ worldInfoCache: new Map(), allowScopedScripts: () => { enabled = true; } }));
    const target = { avatar: 'test.png', book: '已有世界书' };
    await manager.run(target, 'world', 'install'); await manager.run(target, 'world', 'install');
    assert.equal(writes, 1);
    assert.equal(storedBook.custom, '保留世界书配置');
    assert.equal(Object.keys(storedBook.entries).length, 4);
    for (const original of originals) assert.deepEqual(Object.values(storedBook.entries).find(entry => entry.comment === original.comment).content, original.content);
    await manager.run(target, 'regex', 'install'); await manager.run(target, 'regex', 'install');
    assert.deepEqual(storedCard.data.extensions.regex_scripts.slice(1), regexes);
    assert.equal(enabled, true);
    await manager.run(target, 'hide', 'install');
    const preserved = structuredClone(storedCard.data.extensions.regex_scripts);
    await manager.run(target, 'social', 'install');
    const installedWrites = writes;
    await manager.run(target, 'social', 'install');
    assert.equal(writes, installedWrites);
    assert.deepEqual(storedCard.data.extensions.regex_scripts.slice(preserved.length), socialRegexes);
    assert.equal((await manager.run(target, 'social', 'check')).statuses.every(item => item.status === '已安装'), true);
    const dynamic = storedCard.data.extensions.regex_scripts.find(item => item.id === socialRegexes[0].id);
    dynamic.replaceString += '用户修改';
    assert.equal((await manager.run(target, 'social', 'update')).confirm, true);
    assert.ok(storedCard.data.extensions.regex_scripts.find(item => item.id === dynamic.id).replaceString.endsWith('用户修改'));
    await manager.run(target, 'social', 'update', true);
    assert.deepEqual(storedCard.data.extensions.regex_scripts.slice(preserved.length), socialRegexes);
    await manager.run(target, 'social', 'delete');
    assert.deepEqual(storedCard.data.extensions.regex_scripts, preserved);
    const modified = storedCard.data.extensions.regex_scripts[2]; modified.replaceString += '用户修改';
    const guarded = await manager.run(target, 'regex', 'delete');
    assert.equal(guarded.confirm, true);
    assert.ok(guarded.protectedNames.includes(modified.scriptName));
    await manager.run(target, 'world', 'delete');
    assert.deepEqual(Object.values(storedBook.entries), [unrelated]);
    const manual = planResources(regexes, regexes, {}, 'delete', true);
    assert.equal(manual.protectedNames.length, regexes.length);
});

test('display-only phone handoff regex removes blocks without touching surrounding text or source', () => {
    const original = '原正文\n<phone_events>\n{"pocket":1,"events":[]}\n</phone_events>\n后文';
    const expression = new RegExp(HIDE_EVENTS.findRegex.slice(1, HIDE_EVENTS.findRegex.lastIndexOf('/')), 'gi');
    assert.equal(original.replace(expression, HIDE_EVENTS.replaceString), '原正文\n\n后文');
    assert.ok(original.includes('"pocket":1'));
    assert.equal(HIDE_EVENTS.markdownOnly, true); assert.equal(HIDE_EVENTS.promptOnly, false);
});

