test('cloud settings merge adopts remote edits while retaining new local edits and deleted presets', () => {
    const { mergeBackupData, stateHashes, backupState } = require('../src/portable.cjs');
    const { phoneSettings } = require('../src/context.cjs');
    const { configuration } = require('../src/image-service.cjs');
    const local = { events: [], phone: { settings: phoneSettings(), image: configuration({ promptPresets: [{ id: 'old', name: '旧方案', values: {} }] }) } };
    local.people = [{ id: 'local:one', name: '朋友', notes: '旧备注' }];
    local.threads = [{ id: 'group:one', name: '旧群名', members: [PLAYER, 'local:one'] }];
    local.photos = [{ id: 'one', asset: 'original', prompt: 'old prompt' }];
    const base = stateHashes(backupState(local));
    const remote = structuredClone(local);
    remote.people[0].notes = '远端新备注'; remote.threads[0].name = '远端新群名'; remote.photos[0].prompt = 'new prompt';
    local.photos[0].asset = 'device-specific'; remote.phone.image.imageRules = '另一台设备的新规则'; remote.phone.settings.theme = 'dark';
    local.phone.image.promptPresets = []; local.phone.settings.socialCommonPrompt = '本机新写的规则';
    const merged = mergeBackupData(local, remote, base);
    assert.equal(merged.phone.image.imageRules, '另一台设备的新规则');
    assert.equal(merged.phone.settings.theme, 'dark');
    assert.equal(merged.phone.settings.socialCommonPrompt, '本机新写的规则');
    assert.deepEqual(merged.phone.image.promptPresets, []);
    assert.equal(merged.people[0].notes, '远端新备注');
    assert.equal(merged.threads[0].name, '远端新群名');
    assert.equal(merged.photos[0].prompt, 'new prompt');
    assert.equal(merged.photos[0].asset, 'device-specific');
    const fresh = mergeBackupData({ phone: { settings: phoneSettings(), image: configuration() } }, remote);
    assert.equal(fresh.phone.image.imageRules, '另一台设备的新规则');
    assert.equal(fresh.phone.settings.theme, 'dark');
    const photos = mergeBackupData({ photos: [], deletedPhotos: ['gone'] }, { photos: [{ id: 'gone', asset: 'old' }], photoAssets: { old: { data: 'old' } } });
    assert.deepEqual(photos.photos, []); assert.deepEqual(photos.photoAssets, {});
});

